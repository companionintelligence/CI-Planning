// Capture listing media for the README: a first-run (FTUE) screencast and
// per-view gallery screenshots. Not a test — run directly with node against a
// running app:  APP_URL=http://localhost:3848 MODE=ftue node capture-listing.mjs
import { chromium } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

const URL = process.env.APP_URL || 'http://localhost:3848';
const MODE = process.env.MODE || 'gallery';
const OUT = process.env.OUT_DIR || '/tmp/ci-frames';
const SHOT_DIR = process.env.SHOT_DIR || path.resolve('../../docs/screenshots');
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(SHOT_DIR, { recursive: true });

const VIEWPORT = { width: 1280, height: 800 };

function tomorrowISO() {
  const d = new Date();
  d.setDate(d.getDate() + 1);
  return d.toISOString().slice(0, 10);
}

async function runFtue() {
  const browser = await chromium.launch();
  // Pin the browser TZ to UTC so the client's "today" matches the server (TZ=UTC)
  // — otherwise the client fetches a different day's blocks than were scheduled.
  const ctx = await browser.newContext({
    viewport: VIEWPORT,
    timezoneId: 'UTC',
    locale: 'en-US',
    recordVideo: { dir: OUT, size: VIEWPORT },
  });
  const page = await ctx.newPage();
  const pause = (ms) => page.waitForTimeout(ms);
  const t0 = Date.now(); // video timeline ~starts at first page

  try {
    await page.goto(URL, { waitUntil: 'domcontentloaded' });
    // Wait for the AI briefing to render so the clean-slate card is on screen.
    // The summary is generated by Ollama on each load (~12s), which is dead time
    // at the head of the recording — log when it appears so the GIF can trim it.
    await page.getByText(/AI Briefing|Day Overview/i).first().waitFor({ state: 'visible', timeout: 40000 });
    const leadSeconds = (Date.now() - t0) / 1000;
    fs.writeFileSync(path.join(OUT, 'trim.txt'), String(leadSeconds));
    await pause(2400); // hold on the empty "clean slate" Today + AI briefing

    // Open the task composer
    await page.locator('button.fab').click();
    await pause(900);

    // Type the first task
    const title = page.locator('input.input-lg');
    await title.click();
    await title.pressSequentially('Draft the Q3 board deck', { delay: 65 });
    await pause(600);

    // Pick a priority
    await page.getByRole('button', { name: 'P2', exact: true }).click();
    await pause(700);

    // Reveal and fill the detail fields
    await page.getByRole('button', { name: /More options/ }).click();
    await pause(600);
    await page.locator('input[type=date]').fill(tomorrowISO());
    await pause(400);
    await page.locator('input[type=number]').fill('60');
    await pause(900);

    // Create it — task lands in Open Tasks live
    await page.getByRole('button', { name: 'Create Task' }).click();
    await page.getByText('Draft the Q3 board deck').first().waitFor({ state: 'visible', timeout: 10000 });
    await pause(1800);

    // Let the planner place it on the day — block shows up in "Next Up"
    await page.getByRole('button', { name: 'Auto-schedule' }).click();
    await page.getByText('No blocks scheduled').waitFor({ state: 'hidden', timeout: 15000 });
    await pause(2800);
  } catch (err) {
    console.error('FTUE flow error (saving partial video):', err.message);
  } finally {
    await ctx.close(); // flush the video to disk even on error
    await browser.close();
  }

  // Rename the (hashed) webm to a stable path
  const webm = fs.readdirSync(OUT).find((f) => f.endsWith('.webm'));
  const stable = path.join(OUT, 'ftue.webm');
  if (webm) fs.renameSync(path.join(OUT, webm), stable);
  console.log('FTUE video:', stable);
}

async function runGallery() {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: VIEWPORT, deviceScaleFactor: 2, timezoneId: 'UTC', locale: 'en-US' });
  const page = await ctx.newPage();
  const views = [
    ['/', 'today'],
    ['/calendar', 'calendar'],
    ['/inbox', 'inbox'],
    ['/tasks', 'tasks'],
    ['/tags', 'tags'],
    ['/jobs', 'jobs'],
    ['/settings', 'settings'],
  ];
  for (const [route, name] of views) {
    await page.goto(URL + route, { waitUntil: 'domcontentloaded' });
    if (name === 'today') {
      // The AI briefing is generated by Ollama on load (~12s) — wait for it so
      // the hero screenshot shows the real briefing, not a half-rendered page.
      await page
        .getByText(/AI Briefing|Day Overview/i)
        .first()
        .waitFor({ state: 'visible', timeout: 40000 })
        .catch(() => {});
    }
    await page.waitForTimeout(1500); // let lists/animations settle
    const out = path.join(SHOT_DIR, `${name}.png`);
    await page.screenshot({ path: out });
    console.log('shot:', out);
  }
  await browser.close();
}

if (MODE === 'ftue') await runFtue();
else await runGallery();
